-- Esquema de la práctica académica UNIAJC (PostgreSQL / Neon).
--
-- Replica la estructura de la base compartida del profesor (columnas en
-- español, según el diagrama del README). Si usas la base del profesor NO
-- necesitas ejecutarlo: las tablas ya existen. Sirve para crear tu propia
-- base en Neon con la misma estructura. Por usar IF NOT EXISTS, ejecutarlo
-- de nuevo no borra ni modifica nada.

CREATE SCHEMA IF NOT EXISTS "practica-mvc";

CREATE TABLE IF NOT EXISTS "practica-mvc".estudiantes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    lastname VARCHAR(100),
    email VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS "practica-mvc".docentes (
    id_docente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    especialidad VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS "practica-mvc".materias (
    id_materia SERIAL PRIMARY KEY,
    nombre_materia VARCHAR(100) NOT NULL,
    creditos INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS "practica-mvc".grupos (
    id_grupo SERIAL PRIMARY KEY,
    id_materia INTEGER NOT NULL,
    id_docente INTEGER NOT NULL,
    aula VARCHAR(50) NOT NULL,
    horario VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS "practica-mvc".inscripciones (
    id_inscripcion SERIAL PRIMARY KEY,
    id_estudiante INTEGER NOT NULL,
    id_grupo INTEGER NOT NULL,
    nota_final DOUBLE PRECISION DEFAULT 0.0,
    estado VARCHAR(20) NOT NULL
);

-- La base del profesor no tiene llaves foráneas ni restricciones UNIQUE/CHECK:
-- la integridad (emails únicos, materias y docentes existentes, notas de 0 a 5,
-- inscripciones sin duplicar, etc.) la garantiza la capa de servicios.
